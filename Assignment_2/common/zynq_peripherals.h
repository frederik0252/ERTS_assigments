#ifndef ERTS_ZYNQ_PERIPHERALS_H
#define ERTS_ZYNQ_PERIPHERALS_H

#include "xparameters.h"

/* SDT looks up GPIO by base address; SDK BSPs look it up by device ID. */
#ifdef SDT
#ifdef XPAR_SWITCHES_BASEADDR
#define ERTS_SWITCHES_CONFIG_KEY XPAR_SWITCHES_BASEADDR
#endif
#else
#ifdef XPAR_SWITCHES_DEVICE_ID
#define ERTS_SWITCHES_CONFIG_KEY XPAR_SWITCHES_DEVICE_ID
#endif
#endif

/* The supplied platform has a custom led_ip, not an AXI GPIO LED device. */
#if defined(XPAR_LED_IP_0_BASEADDR)
#define ERTS_LED_BASEADDR XPAR_LED_IP_0_BASEADDR
#elif defined(XPAR_LED_IP_0_S_AXI_BASEADDR)
#define ERTS_LED_BASEADDR XPAR_LED_IP_0_S_AXI_BASEADDR
#elif defined(XPAR_LED_IP_BASEADDR)
#define ERTS_LED_BASEADDR XPAR_LED_IP_BASEADDR
#elif defined(XPAR_LED_IP_S_AXI_BASEADDR)
#define ERTS_LED_BASEADDR XPAR_LED_IP_S_AXI_BASEADDR
#endif

/* The packaged course IP uses S00_AXI, while the handout prints S_AXI. */
#if defined(XPAR_MATRIX_IP_0_BASEADDR)
#define ERTS_MATRIX_BASEADDR XPAR_MATRIX_IP_0_BASEADDR
#elif defined(XPAR_MATRIX_IP_0_S00_AXI_BASEADDR)
#define ERTS_MATRIX_BASEADDR XPAR_MATRIX_IP_0_S00_AXI_BASEADDR
#elif defined(XPAR_MATRIX_IP_0_S_AXI_BASEADDR)
#define ERTS_MATRIX_BASEADDR XPAR_MATRIX_IP_0_S_AXI_BASEADDR
#elif defined(XPAR_MATRIX_IP_BASEADDR)
#define ERTS_MATRIX_BASEADDR XPAR_MATRIX_IP_BASEADDR
#elif defined(XPAR_MATRIX_IP_S00_AXI_BASEADDR)
#define ERTS_MATRIX_BASEADDR XPAR_MATRIX_IP_S00_AXI_BASEADDR
#elif defined(XPAR_MATRIX_IP_S_AXI_BASEADDR)
#define ERTS_MATRIX_BASEADDR XPAR_MATRIX_IP_S_AXI_BASEADDR
#endif

#endif
